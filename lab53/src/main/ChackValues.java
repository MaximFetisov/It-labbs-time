package main;

/**
 * Утилитный класс для проверки и валидации пользовательского ввода.
 * Содержит статические методы, которые обеспечивают корректность вводимых данных,
 * предотвращая сохранение пустых или некорректных значений.
 *
 * @author Максим
 * @see Run#inout
 */
public class ChackValues {
    /**
     * Проверяет введённое значение на пустоту и возвращает корректную строку.
     * Если введена пустая строка, запрашивает ввод повторно до получения непустого значения.
     *
     * @param name имя поля для вывода в сообщении об ошибке
     * @return введённая строка без ведущих и замыкающих пробелов
     */
    public static String chackValuesNull(String name) {
        String test = Run.inout.read();
        while (test.trim().isEmpty()) {
            Run.inout.write(name + " не может быть null");
            Run.inout.write("Введите значение " + name + ":");
            test = Run.inout.read();
        }
        return test.trim();
    }
}